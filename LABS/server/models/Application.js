const mongoose = require("mongoose");

// Same domain and validation rules as the Admissions form in Labs 3, 5 & 6,
// enforced again here so the database never trusts the browser.
const PROGRAMMES = ["B.Tech AI & ML", "B.Tech CSE", "BBA", "BA LLB"];
const CAMPUSES = [
  "Central Campus, Bengaluru",
  "Bannerghatta Road, Bengaluru",
  "Kengeri, Bengaluru",
  "Yeshwanthpur, Bengaluru",
  "Delhi NCR",
  "Pune Lavasa",
];
const STATUSES = ["review", "shortlisted", "admitted", "rejected"];

const applicationSchema = new mongoose.Schema(
  {
    applicationNo: { type: String, unique: true }, // CU-ADM-2026-0001, generated by the server
    name: { type: String, required: [true, "Name is required"], trim: true, minlength: [3, "At least 3 characters"] },
    email: {
      type: String,
      required: [true, "Email is required"],
      trim: true,
      lowercase: true,
      match: [/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/, "Enter a valid email"],
    },
    phone: {
      type: String,
      required: [true, "Phone is required"],
      trim: true,
      match: [/^[6-9]\d{9}$/, "Enter a 10-digit mobile number"],
    },
    programme: { type: String, required: [true, "Choose a programme"], enum: { values: PROGRAMMES, message: "Unknown programme" } },
    campus: { type: String, required: [true, "Choose a campus"], enum: { values: CAMPUSES, message: "Unknown campus" } },
    twelfthPct: {
      type: Number,
      required: [true, "Enter a percentage 0-100"],
      min: [60, "Below the 60% eligibility cut-off"],
      max: [100, "Enter a percentage 0-100"],
    },
    status: { type: String, enum: { values: STATUSES, message: "Unknown status" }, default: "review" },
    sop: { type: String, required: [true, "Statement of purpose is required"], trim: true, minlength: [40, "Write at least 40 characters"] },
  },
  {
    timestamps: true, // createdAt / updatedAt, maintained by Mongoose
    toJSON: {
      // The React app (Labs 5 & 6) expects `id`, not Mongo's `_id` / `__v`.
      transform: (_doc, ret) => {
        ret.id = String(ret._id);
        delete ret._id;
        delete ret.__v;
        return ret;
      },
    },
  }
);

const Application = mongoose.model("Application", applicationSchema);

// Next CU-ADM-<year>-<seq>: one higher than the largest sequence already stored.
async function nextApplicationNo(year = new Date().getFullYear()) {
  const [last] = await Application.find({ applicationNo: new RegExp(`^CU-ADM-${year}-`) })
    .sort({ applicationNo: -1 })
    .limit(1)
    .lean();
  const seq = last ? Number(last.applicationNo.split("-").pop()) : 0;
  return `CU-ADM-${year}-${String(seq + 1).padStart(4, "0")}`;
}

module.exports = { Application, nextApplicationNo };
